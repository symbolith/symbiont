local acp = require 'symbiont.client.acp'

describe('acp', function()
  describe('InitializeRequest', function()
    it('builds request with given params', function()
      local msg = acp.InitializeRequest(1, 'my-client', '1.0.0')
      assert.equals('2.0', msg.jsonrpc)
      assert.equals(1, msg.id)
      assert.equals('initialize', msg.method)
      assert.equals(1, msg.params.protocolVersion)
      assert.equals('my-client', msg.params.clientInfo.name)
      assert.equals('1.0.0', msg.params.clientInfo.version)
    end)
  end)

  describe('ListSessionsRequest', function()
    it('builds request with null cwd by default', function()
      local msg = acp.ListSessionsRequest(1)
      assert.equals('2.0', msg.jsonrpc)
      assert.equals('session/list', msg.method)
      assert.equals(vim.NIL, msg.params.cwd)
      assert.equals('{"cwd":null}', vim.json.encode(msg.params))
    end)

    it('passes cwd when provided', function()
      local msg = acp.ListSessionsRequest(1, '/home/user/project')
      assert.equals('/home/user/project', msg.params.cwd)
    end)
  end)

  describe('NewSessionRequest', function()
    it('builds request with cwd', function()
      local msg = acp.NewSessionRequest(1, '/home/user/project')
      assert.equals('2.0', msg.jsonrpc)
      assert.equals('session/new', msg.method)
      assert.equals('/home/user/project', msg.params.cwd)
    end)
  end)

  describe('LoadSessionRequest', function()
    it('builds request with sessionId and cwd', function()
      local msg = acp.LoadSessionRequest(1, 'sess-1', '/home/user/project')
      assert.equals('2.0', msg.jsonrpc)
      assert.equals('session/load', msg.method)
      assert.equals('sess-1', msg.params.sessionId)
      assert.equals('/home/user/project', msg.params.cwd)
    end)
  end)

  describe('PromptRequest', function()
    it('builds request with sessionId and prompt passthrough', function()
      local prompt = { { type = 'text', text = 'hello' } }
      local msg = acp.PromptRequest(1, 'sess-1', prompt)
      assert.equals('2.0', msg.jsonrpc)
      assert.equals('session/prompt', msg.method)
      assert.equals('sess-1', msg.params.sessionId)
      assert.are.same(prompt, msg.params.prompt)
    end)
  end)

  describe('SetModeRequest', function()
    it('builds request with sessionId and modeId', function()
      local msg = acp.SetModeRequest(1, 'sess-1', 'plan')
      assert.equals('2.0', msg.jsonrpc)
      assert.equals('session/setMode', msg.method)
      assert.equals('sess-1', msg.params.sessionId)
      assert.equals('plan', msg.params.modeId)
    end)
  end)

  describe('SetConfigOptionRequest', function()
    it('builds request with sessionId, configOptionId, and value', function()
      local msg = acp.SetConfigOptionRequest(1, 'sess-1', 'temperature', '0.7')
      assert.equals('2.0', msg.jsonrpc)
      assert.equals('session/setConfigOption', msg.method)
      assert.equals('sess-1', msg.params.sessionId)
      assert.equals('temperature', msg.params.configOptionId)
      assert.equals('0.7', msg.params.value)
    end)
  end)

  describe('CancelNotification', function()
    it('builds notification without id', function()
      local msg = acp.CancelNotification 'sess-1'
      assert.equals('2.0', msg.jsonrpc)
      assert.equals('session/cancel', msg.method)
      assert.equals('sess-1', msg.params.sessionId)
      assert.is_nil(rawget(msg, 'id'))
    end)
  end)

  describe('PermissionSelectedResponse', function()
    it('builds response with selected outcome and optionId', function()
      local msg = acp.PermissionSelectedResponse(42, 'opt-1')
      assert.equals('2.0', msg.jsonrpc)
      assert.equals(42, msg.id)
      assert.equals('selected', msg.result.outcome)
      assert.equals('opt-1', msg.result.optionId)
    end)
  end)

  describe('PermissionCancelledResponse', function()
    it('builds response with cancelled outcome', function()
      local msg = acp.PermissionCancelledResponse(42)
      assert.equals('2.0', msg.jsonrpc)
      assert.equals(42, msg.id)
      assert.equals('cancelled', msg.result.outcome)
      assert.is_nil(rawget(msg.result, 'optionId'))
    end)
  end)
end)
